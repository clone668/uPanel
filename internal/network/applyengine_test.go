// useAddress 改写 `ip` 的回复：模拟内核里这张网卡的现状。
func (f *applyFixture) useAddress(addr string, prefix int, gateway string) {
	f.ip.reply("ip -j addr show", `[
	  {"ifindex":2,"ifname":"ens4","mtu":1500,"operstate":"UP","address":"52:54:00:aa:bb:cc",
	   "addr_info":[{"family":"inet","local":"`+addr+`","prefixlen":`+
		itoa(prefix)+`,"scope":"global","type":"primary"}]}
	]`)
	f.ip.reply("ip -j route show", `[{"dst":"default","gateway":"`+gateway+
		`","dev":"ens4","protocol":"static","metric":100}]`)
}

// useAddrs 让这张网卡上同时挂多个全局地址（地址交接的中途、或别的配置文件也在
// 给这张网卡配地址时，内核里就是这个样子）。
func (f *applyFixture) useAddrs(addrs ...string) {
	parts := make([]string, 0, len(addrs))
	for _, a := range addrs {
		parts = append(parts, `{"family":"inet","local":"`+a+`","prefixlen":24,"scope":"global","type":"primary"}`)
	}
	f.ip.reply("ip -j addr show", `[
	  {"ifindex":2,"ifname":"ens4","mtu":1500,"operstate":"UP","address":"52:54:00:aa:bb:cc",
	   "addr_info":[`+strings.Join(parts, ",")+`]}
	]`)
}

// staticDef 是这次要改成的那一份配置。
func staticDef() *ApplyDefinition {
	return &ApplyDefinition{Mode: ModeStatic, IPv4: &IPv4Setting{
		Address: "10.0.2.15", PrefixLength: 24, Gateway: "10.0.2.1", DNS: []string{"1.1.1.1"}}}
}

// pending 读回唯一那条回滚记录。
func (f *applyFixture) pending(t *testing.T) *RollbackRecord {
	t.Helper()
	names, err := f.fs.ListDir(testStateDir)
	if err != nil {
		t.Fatalf("列状态目录失败: %v", err)
	}
	for _, name := range names {
		if !strings.HasSuffix(name, ".json") {
			continue
		}
		rec, rerr := f.eng.readRecord(strings.TrimSuffix(name, ".json"))
		if rerr != nil {
			t.Fatalf("读记录失败: %v", rerr)
		}
		return rec
	}
	t.Fatalf("状态目录里没有记录：%v", names)
	return nil
}

// panelFileExists 报告面板那份文件在不在。
func (f *applyFixture) panelFileExists() bool {
	_, err := f.fs.ReadFile(testPanelFile)
	return err == nil
}

// applyStatic 走一遍完整的 apply：预检 → 执行，返回执行报告与预检判决。
func (f *applyFixture) applyStatic(t *testing.T) (WriteReport, Assessment) {
	t.Helper()
	ctx := context.Background()
	current := f.eng.Current(ctx)
	assess, err := f.eng.Assess(ctx, ApplyParams{
		InterfaceID: "ens4", ExpectedConfigHash: current.ConfigHash, Definition: staticDef()})
	if err != nil {
		t.Fatalf("预检失败: %v", err)
	}
	if !assess.Allowed {
		t.Fatalf("预检应通过，被拒: %+v", assess.Blockers)
	}
	report, err := f.eng.ExecuteWrite(ctx, WriteRequest{
		Action:               ActionApply,
		Params:               assess.Normalized,
		ExpectedIdentity:     assess.IdentityFingerprint,
		ExpectedStateVersion: assess.StateVersion,
		OperationID:          "op-1",
	})
	if err != nil {
		t.Fatalf("执行失败: %v", err)
	}
	return report, assess
}

// ---- 1. 先武装、再 apply ----

func TestApplyWritesPanelFileAndArmsTimerBeforeApply(t *testing.T) {
	f := newApplyFixture(t)
	// 第一次 `netplan apply` 之后，内核里就是新地址。
	f.cmd.side("netplan apply", func() { f.useAddress("10.0.2.15", 24, "10.0.2.1") })

	report, assess := f.applyStatic(t)

	if report.Outcome != OutcomeVerified {
		t.Fatalf("结果 = %q，期望 %q（observed=%+v）", report.Outcome, OutcomeVerified, report.Observed)
	}

	// 顺序：先 generate，再装 timer，最后 apply。
	genAt := f.cmd.indexOf("netplan generate")
	armAt := f.cmd.indexOf("systemctl start upanel-netrollback@")
	applyAt := f.cmd.indexOf("netplan apply")
	if genAt < 0 || armAt < 0 || applyAt < 0 {
		t.Fatalf("命令顺序不全: %v", f.cmd.calls)
	}
	if !(genAt < armAt && armAt < applyAt) {
		t.Fatalf("必须先生成、再武装 timer、最后 apply；实际顺序: %v", f.cmd.calls)
	}

	// 面板自己的文件写进去了，而且只有它该有的键。
	data, err := f.fs.ReadFile(testPanelFile)
	if err != nil {
		t.Fatalf("面板文件没写出来: %v", err)
	}
	for _, want := range []string{"10.0.2.15/24", "via: 10.0.2.1", "1.1.1.1", "dhcp4: false"} {
		if !strings.Contains(string(data), want) {
			t.Errorf("面板文件里应有 %q，实际:\n%s", want, data)
		}
	}

	// 记录是 pending、到期时间是 now+120s，并且写得进状态目录。
	rec := f.pending(t)
	if rec.State != StatePending {
		t.Errorf("记录状态 = %q，期望 %q", rec.State, StatePending)
	}
	if rec.CandidateAddress != "10.0.2.15" || rec.Interface != "ens4" {
		t.Errorf("记录内容不对: %+v", rec)
	}
	if got, want := rec.Deadline, f.clock.Now().Add(RollbackWindow).Format(time.RFC3339); got != want {
		t.Errorf("到期时间 = %q，期望 %q", got, want)
	}
	if rec.Previous.Address != "192.168.1.10" || rec.Previous.PanelFilePresent {
		t.Errorf("改之前的样子记错了: %+v", rec.Previous)
	}
	// 窗口是 120 秒这件事要在结果里露出来（页面据此倒计时）。
	if got := report.Data["window_seconds"]; got != 120 {
		t.Errorf("window_seconds = %v，期望 120", got)
	}
	// timer 的窗口写进了单元文件。
	timer, err := f.fs.ReadFile(testSystemdDir + "/upanel-netrollback@" + rec.Token + ".timer")
	if err != nil {
		t.Fatalf("timer 单元没写出来: %v", err)
	}
	if !strings.Contains(string(timer), "OnActiveSec=120s") {
		t.Errorf("timer 里应有 OnActiveSec=120s:\n%s", timer)
	}
	// 模板单元用 %i，不把 token 写死进去。
	svc, err := f.fs.ReadFile(testSystemdDir + "/upanel-netrollback@.service")
	if err != nil {
		t.Fatalf("模板单元没写出来: %v", err)
	}
	if !strings.Contains(string(svc), "--token %i") {
		t.Errorf("模板单元必须用 %%i 取实例名:\n%s", svc)
	}
	if strings.Contains(string(svc), rec.Token) {
		t.Errorf("模板单元里不该出现具体 token:\n%s", svc)
	}

	// 预检的显示名与影响要能读：确认页面上并列显示"改成什么"。
	if !strings.Contains(assess.DisplayName, "ens4") {
		t.Errorf("显示名应带网卡: %q", assess.DisplayName)
	}
	var sawManagement bool
	for _, w := range assess.Warnings {
		if w.Code == CodeManagementPath {
			sawManagement = true
		}
	}
	if !sawManagement {
		t.Errorf("默认路由全在 ens4 上，应有 NETWORK_MANAGEMENT_PATH 告警: %+v", assess.Warnings)
	}
}

