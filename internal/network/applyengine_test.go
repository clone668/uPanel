// ---- 测试替身 ----

// fakeClock 是可控时钟。回滚窗口是 120 秒，测试不能真的等它。
type fakeClock struct{ t time.Time }

func newFakeClock() *fakeClock {
	return &fakeClock{t: time.Date(2026, 10, 26, 12, 0, 0, 0, time.UTC)}
}

func (c *fakeClock) Now() time.Time          { return c.t }
func (c *fakeClock) advance(d time.Duration) { c.t = c.t.Add(d) }

// fakeCmd 是 CommandRunner 的替身，按 "程序名 参数..." 匹配预设，并能挂副作用。
type fakeCmd struct {
	results map[string]syscmd.Result
	errs    map[string]error
	// errPrefix 按前缀返回错误：token 是随机生成的，测试没法预知单元名。
	errPrefix map[string]error
	onCall    map[string]func()
	calls     []string
}

func newFakeCmd() *fakeCmd {
	return &fakeCmd{results: map[string]syscmd.Result{}, errs: map[string]error{},
		errPrefix: map[string]error{}, onCall: map[string]func(){}}
}

// set 让某条命令以指定退出码结束。
func (c *fakeCmd) set(key string, code int) *fakeCmd {
	c.results[key] = syscmd.Result{ExitCode: code}
	return c
}

// fail 让某条命令"跑不起来"（启动失败，不是非零退出）。
func (c *fakeCmd) fail(key string, err error) *fakeCmd { c.errs[key] = err; return c }

// failPrefix 让所有以某前缀开头的命令失败。
func (c *fakeCmd) failPrefix(prefix string, err error) *fakeCmd {
	c.errPrefix[prefix] = err
	return c
}

// side 给某条命令挂副作用（用来模拟"命令改了内核状态"）。
func (c *fakeCmd) side(key string, fn func()) *fakeCmd { c.onCall[key] = fn; return c }

func (c *fakeCmd) Run(_ context.Context, spec syscmd.Spec, _ syscmd.Limits) (syscmd.Result, error) {
	key := path.Base(spec.Program) + " " + strings.Join(spec.Args, " ")
	c.calls = append(c.calls, key)
	if fn, ok := c.onCall[key]; ok {
		fn()
	}
	if err, ok := c.errs[key]; ok {
		return syscmd.Result{ExitCode: -1}, err
	}
	for prefix, err := range c.errPrefix {
		if strings.HasPrefix(key, prefix) {
			return syscmd.Result{ExitCode: -1}, err
		}
	}
	res := c.results[key]
	if res.ExitCode != 0 {
		return res, &syscmd.ExitError{Program: spec.Program, ExitCode: res.ExitCode}
	}
	return res, nil
}

// called 报告某条命令被调用了几次。
func (c *fakeCmd) called(key string) int {
	n := 0
	for _, call := range c.calls {
		if call == key {
			n++
		}
	}
	return n
}

// indexOf 返回某条命令第一次出现的下标；前缀匹配（单元名里带随机 token）。
func (c *fakeCmd) indexOf(prefix string) int {
	for i, call := range c.calls {
		if strings.HasPrefix(call, prefix) {
			return i
		}
	}
	return -1
}

