// ---- 3. 退出码 0 但结果不对：自己退回去 ----

func TestApplyRollsBackWhenKernelDisagrees(t *testing.T) {
	f := newApplyFixture(t)
	// 第一次 apply：地址上去了，但网关没变（这一步模拟"退出码 0、结果不对"）。
	// 第二次 apply（回滚时）：旧配置真的回来了。
	applied := 0
	f.cmd.side("netplan apply", func() {
		applied++
		if applied == 1 {
			f.useAddress("10.0.2.15", 24, "192.168.1.1")
			return
		}
		f.useAddress("192.168.1.10", 24, "192.168.1.1")
	})

	report, _ := f.applyStatic(t)

	if report.Outcome != OutcomeRolledBack {
		t.Fatalf("结果 = %q，期望 %q（observed=%+v）", report.Outcome, OutcomeRolledBack, report.Observed)
	}
	if n := f.cmd.called("netplan apply"); n != 2 {
		t.Fatalf("apply 应被调用两次（一次改、一次退），实际 %d 次: %v", n, f.cmd.calls)
	}
	rec := f.pending(t)
	if rec.State != StateRolledBack {
		t.Errorf("记录状态 = %q，期望 %q（result=%s）", rec.State, StateRolledBack, rec.Result)
	}
	if f.panelFileExists() {
		t.Errorf("回滚之后不该留下面板文件")
	}
}

