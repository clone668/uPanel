// TestApplyDHCPRollsBackWhenAnotherFileAlsoConfigures 是上一条的反面：
// 网卡上一直挂着两个全局地址，说明**别的** netplan 文件也在给这张网卡配地址，
// 我们这份 `dhcp4: true` 并没有真正接管——这时必须回滚，而不是报"改好了"。
func TestApplyDHCPRollsBackWhenAnotherFileAlsoConfigures(t *testing.T) {
	f := newApplyFixture(t)
	// 等窗口压成 0：这条分支靠真实定时器走完 30 秒，单测里靠"时钟不动 + 零点到期"直接收口。
	f.eng.dhcpWait = 0
	applied := 0
	f.cmd.side("netplan apply", func() {
		applied++
		if applied == 1 {
			// 改完：旧地址还在，DHCP 的又来了一个 —— 两个并存。
			f.useAddrs("192.168.1.10", "10.0.2.16")
			return
		}
		// 回滚：回到只有一个静态地址。
		f.useAddress("192.168.1.10", 24, "192.168.1.1")
	})
	ctx := context.Background()

	current := f.eng.Current(ctx)
	assess, err := f.eng.Assess(ctx, ApplyParams{
		InterfaceID: "ens4", ExpectedConfigHash: current.ConfigHash,
		Definition: &ApplyDefinition{Mode: ModeDHCP}})
	if err != nil {
		t.Fatalf("预检失败: %v", err)
	}
	report, err := f.eng.ExecuteWrite(ctx, WriteRequest{
		Action: ActionApply, Params: assess.Normalized,
		ExpectedIdentity: assess.IdentityFingerprint, ExpectedStateVersion: assess.StateVersion,
	})
	if err != nil {
		t.Fatalf("执行失败: %v", err)
	}
	if report.Outcome != OutcomeRolledBack {
		t.Fatalf("结果 = %q，期望 %q（observed=%+v）", report.Outcome, OutcomeRolledBack, report.Observed)
	}
	why, _ := report.Observed["verify_error"].(string)
	if !strings.Contains(why, "2 个全局 IPv4") {
		t.Errorf("核验失败的原因应点明网卡上有两个全局地址，实际 %q", why)
	}
	if n := f.cmd.called("netplan apply"); n != 2 {
		t.Fatalf("apply 应被调用两次（一次改、一次退），实际 %d 次: %v", n, f.cmd.calls)
	}
}

