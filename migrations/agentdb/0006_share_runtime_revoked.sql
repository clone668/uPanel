-- 代理数据库第 6 条迁移：共享的运行时撤销现场（CONTRACTS.md 7.3；P08.3）。
--
-- 为什么需要这一列：P08.3 起，代理每 30 秒检查一次“启用中的共享绑定的卷还挂着吗”，
-- 卷掉线时把那一条共享从托管配置里摘掉，并把现场（时间、卷、当时的观测状态、原因）
-- 记在共享记录上。这个现场是页面告诉用户“为什么这条共享不见了、该怎么办”的唯一依据，
-- 所以它必须落在库里，而不是只活在这一次运行的进程内存里。
--
-- 这一列在验收里是被真机抓出来的：实现先写了结构体字段，但**没有**为它加迁移，
-- 于是 `runtime_revoked` 在 API 上永远是 null，而且每轮对账都会把 updated_at 推到当下
-- （因为“还没记过撤销”这个判断永远成立）。字段有、库里没有，等于功能没做。
--
-- runtime_revoked_json 列语义：
--   空串        这条共享没有在运行时因为卷离线被撤销过
--   非空        RuntimeRevocation 的 JSON：at / volume_id / volume_name / volume_state / reason
--
-- 存 JSON 而不是五个列：没有任何查询按这些字段过滤或排序，它们只被整份读出展示与审计。
-- 拆成五列会让人以为“可以按卷查撤销历史”，而那个问题应该查审计日志。
-- 不加 CHECK(json_valid(...))：与 definition_json 一样，写侧只会写自己 marshal 出来的
-- 结构，读侧解析失败会**报错**而不是返回零值——校验放在能说清原因的地方。

ALTER TABLE shares ADD COLUMN runtime_revoked_json TEXT NOT NULL DEFAULT '';
